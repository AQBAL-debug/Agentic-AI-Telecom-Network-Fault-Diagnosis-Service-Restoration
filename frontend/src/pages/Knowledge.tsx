// pages/Knowledge.tsx - Knowledge Base (Requirements 10 and 11): ask questions answered by RAG
// over approved SOPs (with cited document + section), keyword search, document list and the
// historical incident library with similarity search.
import { useState } from "react";
import { get, post } from "../api";
import { usePoll } from "../hooks";
import { Panel, PageHeader, Empty } from "../components/ui";

export default function Knowledge() {
  const [q, setQ] = useState("What troubleshooting procedure applies to an interface down alarm?");
  const [ans, setAns] = useState<any>(null);
  const [busy, setBusy] = useState(false);
  const [hq, setHq] = useState("aggregation router interface down multiple downstream sites lost");
  const [hist, setHist] = useState<any[] | null>(null);
  const { data: docs } = usePoll<any[]>("/api/kb/documents", 0);
  const { data: all } = usePoll<any[]>("/api/historical", 0);

  async function ask() { setBusy(true); try { setAns(await post("/api/kb/ask", { question: q })); } finally { setBusy(false); } }

  return (
    <div>
      <PageHeader title="Knowledge Base" sub="Answers come only from approved network-operations documents, and each answer cites the document and section it used." />
      <div className="grid lg:grid-cols-3 gap-4">
        <div className="lg:col-span-2 space-y-4">
          <Panel title="Ask the knowledge base">
            <div className="flex gap-2"><input className="input flex-1" value={q} onChange={(e) => setQ(e.target.value)} onKeyDown={(e) => e.key === "Enter" && ask()} />
              <button className="btn btn-primary" onClick={ask} disabled={busy}>{busy ? "Searching..." : "Ask"}</button></div>
            <div className="flex flex-wrap gap-2 mt-2">{["What should I do when several base stations lose backhaul?", "How do I check whether congestion is the real cause?", "Who must approve a configuration rollback?"].map((s) =>
              <button key={s} className="text-xs text-sig hover:underline" onClick={() => setQ(s)}>{s}</button>)}</div>
            {ans && <div className="mt-4">
              <pre className="whitespace-pre-wrap text-sm font-sans">{ans.answer}</pre>
              <p className="text-xs text-mute mt-2">{ans.llm?.used ? `Generated by ${ans.llm.model}` : "LLM unavailable - showing retrieved procedure text"}</p>
              <h2 className="text-sm mt-4 mb-2">Retrieved sources</h2>
              {ans.sources.map((s: any) => <details key={s.reference} className="py-1.5 border-b border-line/60"><summary className="text-sm cursor-pointer"><span className="text-sig">{s.reference}</span> <span className="text-mute text-xs">score {s.score} - {s.document}</span></summary>
                <pre className="text-xs whitespace-pre-wrap text-mute mt-1">{s.text}</pre></details>)}
            </div>}
          </Panel>
          <Panel title="Historical incident retrieval">
            <div className="flex gap-2"><input className="input flex-1" value={hq} onChange={(e) => setHq(e.target.value)} />
              <button className="btn" onClick={async () => setHist(await get(`/api/historical/similar?q=${encodeURIComponent(hq)}`))}>Find similar</button></div>
            {hist && (hist.length ? hist.map((h) => <div key={h.id} className="text-sm py-2 border-b border-line/60"><span className="id text-sig">{h.id}</span> {h.title} <span className="text-mute">similarity {h.similarity}</span>
              <div className="text-xs text-mute">Root cause: {h.root_cause}. Resolution: {h.resolution}</div></div>) : <Empty>No similar incident</Empty>)}
            <p className="text-xs text-mute mt-2">Past incidents are evidence only; the current root cause must be verified independently.</p>
          </Panel>
        </div>
        <div className="space-y-4">
          <Panel title="Documents">{docs?.map((d) => <details key={d.file} className="py-1"><summary className="text-sm cursor-pointer">{d.document}</summary><ul className="text-xs text-mute pl-4 mt-1">{d.sections.map((s: string) => <li key={s}>{s}</li>)}</ul></details>)}</Panel>
          <Panel title="Historical incident library">{all?.map((h) => <div key={h.id} className="text-xs py-1"><span className="id text-sig">{h.id}</span> {h.title} <span className="text-mute">({h.root_cause_category})</span></div>)}</Panel>
        </div>
      </div>
    </div>
  );
}
