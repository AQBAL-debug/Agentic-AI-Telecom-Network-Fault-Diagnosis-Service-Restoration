"""
report.py
---------
WHAT IT DOES:
    Generates the downloadable PDF NETWORK-INCIDENT REPORT (ReportLab) with the 16
    sections required by the assignment:
      1 Incident ID, 2 Timeline, 3 Correlated alarms, 4 Affected elements,
      5 Topology analysis, 6 Performance analysis, 7 Service impact, 8 Anomaly findings,
      9 Root-cause hypotheses, 10 Historical incidents, 11 Troubleshooting references,
      12 Restoration actions, 13 Human approvals, 14 Post-restoration validation,
      15 Confirmed root cause, 16 Closure summary.
"""
from io import BytesIO
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

styles = getSampleStyleSheet()
H = ParagraphStyle("h", parent=styles["Heading2"], textColor=colors.HexColor("#12355B"), spaceBefore=10)
B = ParagraphStyle("b", parent=styles["BodyText"], fontSize=9, leading=12)
S = ParagraphStyle("s", parent=B, fontSize=8, leading=10)


def P(text, st=B):
    return Paragraph(escape(str(text)), st)


def table(rows, widths=None):
    data = [[P(c, S) for c in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#DCE6F0")),
                           ("GRID", (0, 0), (-1, -1), 0.3, colors.grey), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    return t


def build_report(inc, alarms, actions) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
                            title=f"Incident report {inc.id}")
    s = []
    corr, fl, perf = inc.correlation or {}, inc.fault_localization or {}, inc.performance or {}
    imp, rca, plan, val = inc.service_impact or {}, inc.rca or {}, inc.restoration_plan or {}, inc.validation or {}

    s.append(Paragraph(f"Network Incident Report - {escape(inc.id)}", styles["Title"]))
    s.append(P(f"Generated by Agentic AI NOC Decision-Support Platform. Status: {inc.status}. Severity: {inc.severity}. Revision: {inc.revision}"))

    s.append(Paragraph("1. Incident ID", H)); s.append(P(f"{inc.id} - {inc.title} (created {inc.created_at:%Y-%m-%d %H:%M:%S} UTC)"))
    s.append(Paragraph("2. Incident Timeline", H))
    s.append(table([["Time", "Event"]] + [[t["time"][:19], t["event"]] for t in (inc.timeline or [])[:40]], [40 * mm, 140 * mm]))

    s.append(Paragraph("3. Correlated Alarms", H))
    s.append(table([["Time", "Device", "Alarm", "Severity", "Role"]] +
                   [[a.timestamp.strftime("%H:%M:%S"), a.device, a.alarm_type, a.severity, a.role] for a in alarms if a.role != "duplicate"][:50]))
    s.append(P(f"Duplicates suppressed from view (kept for audit): {sum(a.role == 'duplicate' for a in alarms)}. "
               f"Correlation reasoning: {'; '.join(corr.get('reasoning', []))}", S))

    s.append(Paragraph("4. Affected Network Elements", H))
    s.append(P(", ".join(sorted(set(corr.get("devices", [])) | set(imp.get("unavailable_devices", [])) | set(imp.get("degraded_devices", [])))) or "None"))

    s.append(Paragraph("5. Topology Analysis / Fault Localization", H))
    top = fl.get("primary") or {}
    s.append(P(fl.get("headline", "n/a")))
    for e in top.get("evidence", []):
        s.append(P(f"- {e}", S))
    for e in top.get("contradicting_evidence", []):
        s.append(P(f"- Contradicting: {e}", S))
    s.append(table([["Alternative", "Type", "Score", "Confidence"]] +
                   [[h["location"], h["type"], h["score"], h["confidence"]] for h in fl.get("alternatives", [])]))

    s.append(Paragraph("6. Performance Analysis", H))
    rows = [["Device", "Metric", "Before", "Current", "Change %"]]
    for dev, m in list((perf.get("comparison") or {}).items())[:6]:
        for k in ("latency_ms", "packet_loss_pct", "jitter_ms", "utilization_pct"):
            rows.append([dev, k, m[k]["before"], m[k]["current"], m[k]["change_pct"]])
    s.append(table(rows))
    for c in perf.get("investigation", []):
        s.append(P(f"- {c['check']}: {c['result']} ({'; '.join(map(str, c['evidence']))[:200]})", S))

    s.append(Paragraph("7. Service Impact", H)); s.append(P(imp.get("summary", "n/a")))
    s.append(table([["Service", "Status", "Region", "Customers", "Reason"]] +
                   [[x["service_id"], x["status"], x["region"], x["customers"], x["reason"]] for x in imp.get("affected_services", [])]))
    s.append(P("Redundancy: " + "; ".join(imp.get("redundancy", [])), S))

    s.append(Paragraph("8. Anomaly Findings", H)); s.append(P(perf.get("summary", "n/a")))
    s.append(P(f"Model: {perf.get('model', '')}", S))

    s.append(Paragraph("9. Root-Cause Hypotheses (suspected)", H)); s.append(P(rca.get("summary", "")))
    s.append(table([["#", "Hypothesis", "Conf.", "Supporting", "Contradicting", "Verification"]] +
                   [[h.get("rank"), h["hypothesis"], h["confidence"], "; ".join(h["supporting_evidence"]),
                     "; ".join(h["contradicting_evidence"]), "; ".join(h["required_verification"])] for h in rca.get("hypotheses", [])],
                   [8 * mm, 35 * mm, 12 * mm, 45 * mm, 40 * mm, 40 * mm]))

    s.append(Paragraph("10. Historical Incidents", H))
    s.append(table([["ID", "Title", "Root cause", "Similarity"]] + [[h["id"], h["title"], h["root_cause"], h["similarity"]] for h in inc.historical or []]))

    s.append(Paragraph("11. Troubleshooting References", H))
    for k in (plan.get("procedures") or inc.knowledge or [])[:5]:
        s.append(P(f"- {k['reference']} ({k['document']})", S))

    s.append(Paragraph("12. Restoration Actions", H))
    s.append(table([["Step", "Action", "Category", "Status", "Assigned", "Result"]] +
                   [[a.step, a.description, a.category, a.status, a.assigned_to, a.result] for a in actions],
                   [10 * mm, 60 * mm, 28 * mm, 20 * mm, 30 * mm, 32 * mm]))

    s.append(Paragraph("13. Human Approvals", H))
    appr = [[a.id, a.description[:60], a.status, a.approved_by or "-", a.remarks] for a in actions if a.approved_by or a.status == "rejected"]
    s.append(table([["Action", "Description", "Decision", "By", "Remarks"]] + appr) if appr else P("No approvals recorded yet"))
    s.append(P(f"Correlation decision: {inc.correlation_confirmed}", S))
    for c in inc.comments or []:
        s.append(P(f"- {c['time'][:19]} {c['author']}: {c['text']}", S))

    s.append(Paragraph("14. Post-Restoration Validation", H))
    if val:
        s.append(P(val.get("summary", "")))
        rows = [["Device", "Metric", "Baseline", "During", "After", "Pass"]]
        for m in val.get("metrics", []):
            for k in ("latency_ms", "packet_loss_pct", "jitter_ms", "utilization_pct"):
                rows.append([m["device"], k, m[k]["baseline"], m[k]["during"], m[k]["after"], m[k]["pass"]])
        s.append(table(rows))
    else:
        s.append(P("Not yet performed"))

    s.append(Paragraph("15. Confirmed Root Cause", H))
    s.append(P(inc.confirmed_root_cause or "Not confirmed - root cause remains SUSPECTED"))
    s.append(Paragraph("16. Incident Closure Summary", H))
    s.append(P(f"Final status: {inc.status}. " + (val.get("summary", "") if val else "") +
               f" Reviewer verdict: {(inc.review or {}).get('verdict', 'n/a')}."))
    doc.build(s)
    return buf.getvalue()
